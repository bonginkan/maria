/**
 * Generate footer with metadata
 */
function generateFooter(data: MariaTemplateData): string {
  const lines: string[] = [];

  lines.push("## Metadata");
  lines.push("");
  lines.push("```yaml");
  lines.push(`generated_by: MARIA /init command`);
  lines.push(`version: 3.4.2`);
  lines.push(`timestamp: ${data.timestamp}`);
  lines.push(`project_path: ${data.projectPath}`);

  if (data.summary?.stats) {
    lines.push(`files_analyzed: ${data.summary.stats.filesScanned}`);
    lines.push(`scan_duration: ${data.summary.stats.scanDuration}ms`);
  }

  if (data.errors && data.errors.length > 0) {
    lines.push(`errors_encountered: ${data.errors.length}`);
  }

  lines.push("```");
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push(
    "*This documentation was automatically generated by MARIA. For updates, run `maria /init` again.*",
  );

  return lines.join("\n");
}

/**
 * Fallback MARIA.md generator for error scenarios
 */
export function generateFallbackMariaMd(
  error: Error,
  projectPath: string,
): string {
  const data: MariaTemplateData = {
    projectName: path.basename(projectPath),
    projectPath,
    timestamp: new Date().toISOString(),
    errors: [error.message],
  };

  return generateMariaMd(data);
}
