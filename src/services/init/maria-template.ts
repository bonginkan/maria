/**
 * MARIA.md Template Generator
 * Ensures standardized, high-quality documentation output
 */

import * as path from "path";
import type { InitSummary } from "./types";
import type { MonorepoInfo } from "./phase-a";
import type { VisualInsights } from "./insights-tables";
import type { DeepAppendix } from "./deep-appendix";
import { formatInsightsForMarkdown } from "./insights-tables";
import { formatAppendixForMarkdown } from "./deep-appendix";

export interface MariaTemplateData {
  projectName: string;
  projectPath: string;
  timestamp: string;
  summary?: InitSummary;
  monorepo?: MonorepoInfo;
  insights?: VisualInsights;
  appendix?: DeepAppendix;
  errors?: string[];
}

/**
 * Generate standardized MARIA.md content
 * Guarantees minimum quality standards even on errors
 */
export function generateMariaMd(data: MariaTemplateData): string {
  const sections: string[] = [];

  // Header
  sections.push(generateHeader(data));

  // Table of Contents
  sections.push(generateTableOfContents());

  // Overview (Required Section)
  sections.push(generateOverview(data));

  // Quick Start (Required Section)
  sections.push(generateQuickStart(data));

  // Commands (Required Section)
  sections.push(generateCommands(data));

  // Architecture (Required Section)
  sections.push(generateArchitecture(data));

  // Configuration (Required Section)
  sections.push(generateConfiguration(data));

  // Testing (Required Section)
  sections.push(generateTesting(data));

  // Development Workflow
  sections.push(generateDevelopmentWorkflow(data));

  // Visual Insights (if available)
  if (data.insights) {
    sections.push(formatInsightsForMarkdown(data.insights));
  }

  // Troubleshooting
  sections.push(generateTroubleshooting(data));

  // Deep Appendix (if available)
  if (data.appendix) {
    sections.push(formatAppendixForMarkdown(data.appendix));
  }

  // Footer with metadata
  sections.push(generateFooter(data));

  return sections.join("\n\n---\n\n");
}

/**
 * Generate header section
 */
function generateHeader(data: MariaTemplateData): string {
  const lines: string[] = [];

  lines.push(`# ${data.projectName || "Project"} - MARIA Documentation`);
  lines.push("");
  lines.push(
    `> AI-powered project documentation generated by MARIA /init command`,
  );
  lines.push(`> Generated: ${data.timestamp}`);
  lines.push(`> Path: ${data.projectPath}`);

  if (data.errors && data.errors.length > 0) {
    lines.push("");
    lines.push(
      "> ⚠️ **Note**: Documentation generated with partial data due to scan errors.",
    );
  }

  return lines.join("\n");
}

/**
 * Generate table of contents
 */
function generateTableOfContents(): string {
  const lines: string[] = [];

  lines.push("## Table of Contents");
  lines.push("");
  lines.push("- [Overview](#overview)");
  lines.push("- [Quick Start](#quick-start)");
  lines.push("- [Commands](#commands)");
  lines.push("- [Architecture](#architecture)");
  lines.push("- [Configuration](#configuration)");
  lines.push("- [Testing](#testing)");
  lines.push("- [Development Workflow](#development-workflow)");
  lines.push("- [Troubleshooting](#troubleshooting)");
  lines.push("- [Visual Analysis](#visual-analysis)");
  lines.push("- [Deep Technical Appendix](#deep-technical-appendix)");

  return lines.join("\n");
}

/**
 * Generate Overview section (Required, min 300 chars)
 */
function generateOverview(data: MariaTemplateData): string {
  const lines: string[] = [];

  lines.push("## Overview");
  lines.push("");

  if (data.summary?.description) {
    lines.push(data.summary.description);
  } else {
    // Fallback content to ensure minimum character count
    lines.push(
      `${data.projectName || "This project"} is a software application built with modern development practices.`,
    );
    lines.push("");
  }

  // Project type and structure
  if (data.monorepo && data.monorepo.type !== "single") {
    lines.push(`### Project Structure`);
    lines.push("");
    lines.push(
      `This is a **${data.monorepo.type}** monorepo containing ${data.monorepo.stats.totalWorkspaces} workspaces:`,
    );
    lines.push(
      `- **Applications**: ${data.monorepo.structure.apps.length} apps`,
    );
    lines.push(
      `- **Libraries**: ${data.monorepo.structure.libs.length} libraries`,
    );
    lines.push(`- **Tools**: ${data.monorepo.structure.tools.length} tools`);
    lines.push(
      `- **Configurations**: ${data.monorepo.structure.configs.length} config packages`,
    );
  } else {
    lines.push("### Project Type");
    lines.push("");
    lines.push(
      "This is a standalone application project with a single package structure.",
    );
  }

  // Technology stack summary
  if (data.summary?.techStack) {
    lines.push("");
    lines.push("### Technology Stack");
    lines.push("");
    if (data.summary.techStack.languages.size > 0) {
      lines.push(
        `- **Languages**: ${Array.from(data.summary.techStack.languages).join(", ")}`,
      );
    }
    if (data.summary.techStack.frameworks.size > 0) {
      lines.push(
        `- **Frameworks**: ${Array.from(data.summary.techStack.frameworks).join(", ")}`,
      );
    }
    if (data.summary.techStack.packageManager) {
      lines.push(
        `- **Package Manager**: ${data.summary.techStack.packageManager}`,
      );
    }
  }

  // Statistics
  if (data.summary?.stats) {
    lines.push("");
    lines.push("### Project Statistics");
    lines.push("");
    lines.push(`- Total files analyzed: ${data.summary.stats.filesScanned}`);
    lines.push(`- Lines of code: ${data.summary.stats.linesOfCode || "N/A"}`);
    lines.push(`- Test coverage: ${data.summary.stats.testCoverage || "N/A"}`);
  }

  // Ensure minimum character count
  const content = lines.join("\n");
  if (content.length < 300) {
    lines.push("");
    lines.push(
      "This project follows industry best practices for code organization, testing, and deployment. ",
    );
    lines.push(
      "It includes comprehensive tooling for development, testing, and continuous integration. ",
    );
    lines.push(
      "The codebase is structured to support scalability and maintainability.",
    );
  }

  return lines.join("\n");
}

